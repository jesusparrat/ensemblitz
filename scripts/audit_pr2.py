def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--bootstrap", type=int, default=B.BOOT_N, help="stratified block bootstrap replicates"
    )
    args = parser.parse_args()
    if args.bootstrap < 100:
        parser.error("--bootstrap must be at least 100")

    result, _ = B.audit(B.load_cache(), n_boot=args.bootstrap)
    result["code_review"] = _code_review()
    result["market_case_study"] = _market_case_study()
    payload = B.finite(result)
    JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
    MD_OUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUT.write_text(json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=False) + "\n")
    SUMMARY_OUT.write_text(
        json.dumps(summary_payload(payload), indent=2, ensure_ascii=False, allow_nan=False) + "\n"
    )
    MD_OUT.write_text(render(payload))
    print(
        f"PR2 audit written: {JSON_OUT.relative_to(ROOT)}, "
        f"{SUMMARY_OUT.relative_to(ROOT)} and {MD_OUT.relative_to(ROOT)}; "
        f"N={result['n_games']}, blocks={result['bootstrap']['n_blocks']} "
        f"({result['bootstrap']['block_weeks']}w across {result['bootstrap']['n_seasons']} seasons), "
        f"bootstrap={result['bootstrap']['n_boot']}"
    )
    print(
        "population: "
        f"played={result['population']['n_played']}, "
        f"ties={result['population']['n_ties']}, "
        f"missing={result['population']['n_missing_prediction_rows']}, "
        f"invalid={result['population']['n_invalid_probability_rows']}, "
        f"scored={result['population']['n_scored']}"
    )
    for game in result["population"]["excluded_games"]:
        print(f"excluded {game['game_id']}: {', '.join(game['reasons'])}")
    print(
        "paired sources: "
        f"same_game_ids={result['paired_comparison']['same_game_ids']} "
        f"sha256={result['paired_comparison']['game_ids_sha256']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
