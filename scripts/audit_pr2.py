"""Reproducible PR2 statistical audit from the committed component cache.

This command is offline: it reads reports/baseline_components.parquet and frozen repository
artifacts. It does not download nflverse data or call The Odds API.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

from ensemblitz import baseline as B

ROOT = Path(__file__).resolve().parents[1]
JSON_OUT = ROOT / "reports" / "pr2_statistical_audit.json"
MD_OUT = ROOT / "docs" / "audit" / "pr2-statistical-audit.md"


def _pct(value: float | None, digits: int = 2) -> str:
    return "n/d" if value is None else f"{value * 100:.{digits}f}%"


def _num(value: float | None, digits: int = 4) -> str:
    return "n/d" if value is None else f"{value:.{digits}f}"


def _market_case_study() -> dict:
    prediction = json.loads((ROOT / "predictions/2026/week11.json").read_text())
    odds = json.loads((ROOT / "reports/odds/2026_week11.json").read_text())
    game = next(g for g in prediction["games"] if g["game_id"] == "2026_11_IND_HOU")
    quote = next(g for g in odds["games"] if g["game_id"] == "2026_11_IND_HOU")
    return {
        "game_id": game["game_id"],
        "home": game["home_team"],
        "away": game["away_team"],
        "kickoff_utc": game["kickoff_utc"],
        "nflverse_home_probability": game["home_win_prob"]["market"],
        "home_moneyline": game["market"]["home_moneyline"],
        "away_moneyline": game["market"]["away_moneyline"],
        "odds_api_mean_shin_probability": quote["consensus_home_prob_shin"],
        "odds_api_n_books": quote["n_books"],
        "odds_api_fetched_at": odds["odds_fetched_at"],
        "prediction_generated_at": odds["predictions_generated_at"],
        "model_only_home_probability": quote["model_only_home_prob"],
        "model_only_minus_market_gap": quote["gap_model_only"],
        "legacy_mean_multiplicative_probability": 0.8407,
        "interpretation": (
            "The nflverse value is the no-vig probability from -700/+500 moneylines (84.00%). "
            "The Odds API value is the unweighted mean of 42 operator-level Shin probabilities "
            "(85.77%); the legacy unweighted multiplicative mean was 84.07%. The Odds API cache "
            "was fetched at 20:54:38Z and the prediction was generated at 22:07:57Z. These are "
            "different sources and de-vig methods, captured at different times; neither is a "
            "closing quote, and the Odds API cache predates the prediction by 1h 13m 19s."
        ),
    }


def _code_review() -> dict:
    return {
        "walk_forward": (
            "features.build computes every game's features for a (season, week) batch before "
            "updating ratings with that batch's results; Elo and opponent-adjusted EPA state are "
            "therefore pre-week. pipeline._train_mask admits only played games from earlier "
            "seasons/weeks. pipeline.add_ensemble_walk_forward refits stacks on those earlier "
            "out-of-sample component predictions. models.kalman.run_kf also predicts a whole "
            "week before applying that week's results."
        ),
        "kalman_tuning": (
            "kalman.tune explicitly slices season < before_season before likelihood optimisation. "
            "A regression test guards that cutoff. However models/kf_params.json has no per-season "
            "training-window metadata; the checked-in values cannot be independently proven to "
            "have been generated by that code path."
        ),
        "lightgbm": (
            "The walk-forward component path uses _train_mask and refits before each season/week. "
            "The repository contains no reproducible hyperparameter/feature-selection history, "
            "so it cannot prove that manual model selection was not influenced by later seasons."
        ),
        "point_in_time_risk": (
            "Historical schedule fields home_qb_id/away_qb_id and temp/wind feed QB-rate/change "
            "and LightGBM features. The repository does not retain point-in-time snapshots or "
            "availability timestamps for those fields. Actual starter identity and observed game "
            "weather may differ from what was knowable at forecast time. This is a potential "
            "availability leakage risk, not a demonstrated result-leakage bug; its impact is not "
            "quantified in PR2 because doing so requires point-in-time inputs and a separate "
            "controlled re-evaluation."
        ),
        "processed_data_provenance": (
            "contract.data_snapshot hashes data/raw/*.parquet, while feature construction also "
            "reads data/processed/team_games.parquet and qb_games.parquet. Those processed files "
            "are derived from raw inputs but are not directly hashed in the prediction provenance; "
            "stale derived caches remain a reproducibility risk."
        ),
        "injury_lag": (
            "The feature builder uses Out/Doubtful counts from week t-1 or t-2, not the current "
            "week. This avoids direct same-week injury-report leakage, although source publication "
            "timestamps are not retained in the historical feature cache."
        ),
    }


def render(res: dict) -> str:
    pop = res["population"]
    boot = res["bootstrap"]
    lines = [
        "# PR2 Statistical Audit",
        "",
        f"Generated: {res['generated_at']}. Model version: {res['model_version']}.",
        f"Scoring seasons: {res['seasons'][0]}-{res['seasons'][1]}.",
        "",
        "## Population reconciliation",
        "",
        f"- Rows in regular-season scope: {pop['n_rows_in_scope']}",
        f"- Played games: {pop['n_played']}",
        f"- Rows with valid probabilities for every compared source: {pop['n_valid_probability_rows']}",
        f"- Ties: {pop['n_ties']}",
        f"- Rows with missing predictions: {pop['n_missing_prediction_rows']}",
        f"- Rows with invalid probabilities: {pop['n_invalid_probability_rows']}",
        f"- Final scored population: {pop['n_scored']}",
        f"- Excluded from scoring: {pop['n_excluded_from_scoring']}",
        "",
        "The exclusions below are game-level records, not an assumption that every difference is a tie.",
        "",
    ]
    if pop["excluded_games"]:
        for game in pop["excluded_games"]:
            lines.append(
                f"- {game['game_id']} (season {game['season']}, week {game['week']}): "
                + ", ".join(game["reasons"])
                + "."
            )
    else:
        lines.append("- No exclusions.")
    lines += [
        "",
        "## Paired source comparison",
        "",
        f"- Sources: {', '.join(res['paired_comparison']['sources'])}",
        f"- Same game IDs across MODEL_ONLY, MARKET and ENSEMBLE: {res['paired_comparison']['same_game_ids']}",
        f"- Paired N: {res['paired_comparison']['n_games']}",
        f"- SHA-256 of sorted paired game IDs: `{res['paired_comparison']['game_ids_sha256']}`",
        "",
        "| Source | N | Accuracy | Brier | Log loss | Calibration slope |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for key in ("model_only", "market", "ens"):
        row = res["overall"][key]
        lines.append(
            f"| {key.upper()} | {row['n']} | {_pct(row['accuracy'])} | "
            f"{_num(row['brier'])} | {_num(row['log_loss'])} | "
            f"{_num(row['calibration_slope'], 3)} |"
        )
    lines += [
        "",
        "## Paired uncertainty",
        "",
        f"Method: {boot['resampling']}. Unit: {boot['block_unit']}; "
        f"{boot['n_blocks']} complete season blocks; {boot['n_boot']} replicates; "
        f"seed {boot['seed']}; percentile 95% intervals.",
        "",
        "Only eight season clusters are available. The intervals preserve within-season dependence "
        "but have low cluster count and must be treated as coarse uncertainty estimates, not as "
        "high-powered significance tests.",
        "",
        "| Source minus MARKET | Δ log loss | 95% CI | Δ Brier | 95% CI |",
        "|---|---:|---:|---:|---:|",
    ]
    for key in ("model_only", "ens"):
        row = boot["diff_vs_market"][key]
        lines.append(
            f"| {key.upper()} | {_num(row['log_loss'])} | "
            f"[{_num(row['log_loss_ci'][0])}, {_num(row['log_loss_ci'][1])}] | "
            f"{_num(row['brier'])} | "
            f"[{_num(row['brier_ci'][0])}, {_num(row['brier_ci'][1])}] |"
        )
    lines += [
        "",
        "Negative differences favour the first source. The bootstrap share below zero is a "
        "descriptive resampling proportion, not a conventional p-value.",
        "",
        "## High-confidence favourites (75%+)",
        "",
        "| Source | N | Mean predicted | Actual | Overconfidence | 95% CI overconfidence |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for key in ("model_only", "market", "ens"):
        row = res["heavy_favourites_75"][key]
        if row["n"]:
            ci = row.get("overconfidence_pp_ci95")
            ci_text = "n/d" if not ci else f"[{ci[0]:.2f}, {ci[1]:.2f}] pp"
            lines.append(
                f"| {key.upper()} | {row['n']} | {_pct(row['pred'])} | {_pct(row['actual'])} | "
                f"{row['overconfidence_pp']:+.2f} pp | {ci_text} |"
            )
    lines += [
        "",
        "## Leakage and temporal-validity review",
        "",
    ]
    for key, label in (
        ("walk_forward", "Walk-forward state and stacking"),
        ("kalman_tuning", "Kalman hyperparameters"),
        ("lightgbm", "LightGBM"),
        ("point_in_time_risk", "Point-in-time availability risk"),
        ("processed_data_provenance", "Processed-data provenance"),
        ("injury_lag", "Injury features"),
    ):
        lines += [f"### {label}", "", res["code_review"][key], ""]
    m = res["market_case_study"]
    lines += [
        "## Market source and capture semantics",
        "",
        f"IND @ HOU ({m['game_id']}): nflverse no-vig moneyline probability "
        f"{_pct(m['nflverse_home_probability'])}; home/away prices "
        f"{m['home_moneyline']}/{m['away_moneyline']}. The Odds API mean-Shin probability "
        f"{_pct(m['odds_api_mean_shin_probability'])} across {m['odds_api_n_books']} operators. "
        f"Odds capture {m['odds_api_fetched_at']}; prediction generation "
        f"{m['prediction_generated_at']}; kickoff {m['kickoff_utc']}.",
        "",
        m["interpretation"],
        "",
        "The stored nflverse value is calculated from no-vig moneylines when both are present; "
        "the historical baseline's market source is the nflverse schedule closing line, while "
        "the live Odds API value is a separate pre-kickoff snapshot. These must not be combined "
        "or labelled as one quote. The Odds API Shin consensus is an unweighted mean of individual "
        "Shin de-vigged probabilities, not a pooled market calculation.",
        "",
        "## News adjustment policy",
        "",
        "The current prediction path changes only ensemble probability and margin. The headline "
        "uses the no-market stack and remains unchanged; v1 records `news_adjustment.applies_to = "
        "ensemble`. News is not part of the historical baseline because no point-in-time archive "
        "is present. No historical snapshots were rewritten.",
        "",
        "## Odds-data governance",
        "",
        "The public standard terms reviewed 2026-11-26 permit user-facing dashboards and derived "
        "values, while prohibiting redistribution as a standalone raw feed. Current odds reports "
        "retain only the aggregate mean-Shin probability, capture time, and operator count. "
        "Individual prices, operator identifiers, best prices, EV and ensemble-relative edge have "
        "been removed from current report outputs. Account-specific terms may differ.",
        "",
        "## Margin sign convention",
        "",
        "Canonical margin is home minus away. nflverse `spread_line` is positive when the home "
        "team is favoured. The Odds API spread point uses the opposite sign and is converted by "
        "`contract.odds_api_margin_home(point) = -point`. Regression tests cover the conversion "
        "and the nflverse spread fallback.",
        "",
        "## Governance and non-goals",
        "",
        "`AGENTS.md` is already written in English; no language migration was needed. This audit "
        "does not retune weights, alter model hyperparameters, change frozen prediction snapshots, "
        "call The Odds API, or modify site HTML. Potential point-in-time risks are documented, not "
        "silently repaired or retuned.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bootstrap", type=int, default=B.BOOT_N, help="season-block replicates")
    args = parser.parse_args()
    if args.bootstrap < 100:
        parser.error("--bootstrap must be at least 100")

    result, _ = B.audit(B.load_cache(), n_boot=args.bootstrap)
    result["code_review"] = _code_review()
    result["market_case_study"] = _market_case_study()
    payload = B.finite(result)
    JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
    MD_OUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUT.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
    )
    MD_OUT.write_text(render(payload))
    print(
        f"PR2 audit written: {JSON_OUT.relative_to(ROOT)} and {MD_OUT.relative_to(ROOT)}; "
        f"N={result['n_games']}, seasons={result['bootstrap']['n_blocks']}, "
        f"bootstrap={result['bootstrap']['n_boot']}"
    )
    print(
        "population: "
        f"played={result['population']['n_played']}, "
        f"ties={result['population']['n_ties']}, "
        f"missing={result['population']['n_missing_prediction_rows']}, "
        f"invalid={result['population']['n_invalid_probability_rows']}, "
        f"scored={result['population']['n_scored']}"
    )
    for game in result["population"]["excluded_games"]:
        print(f"excluded {game['game_id']}: {', '.join(game['reasons'])}")
    print(
        "paired sources: "
        f"same_game_ids={result['paired_comparison']['same_game_ids']} "
        f"sha256={result['paired_comparison']['game_ids_sha256']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
